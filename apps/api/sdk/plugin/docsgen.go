// ProviderSlotInfo 是文档/SDK 用的槽位说明。
type ProviderSlotInfo struct {
	Slot        string `json:"slot"`
	Description string `json:"description"`
}

// ProviderSlotCatalog 返回带说明的 provider 槽位列表。
func ProviderSlotCatalog() []ProviderSlotInfo {
	// 与 KnownProviderSlots 顺序一致，补充作者可读说明。
	notes := map[string]string{
		"mail.provider":               "Outbound mail transport (e.g. built-in sforum.smtp). Implies net.outbound when selected as a plugin provider.",
		"search.provider":             "Full-text search backend. Core ships Meilisearch; slot reserved for future plugin drivers.",
		"attachment.storage.provider": "Object storage for attachments. Core owns local/OSS/COS/FTP/SFTP drivers in v1; slot name is stable for docs and future plugins.",
		"human_verification.provider": "Human verification / CAPTCHA-style checks (core Altcha default).",
		"auth.risk.provider":          "Login/registration risk signals (core default).",
		"editor.sanitizer.provider":   "Rich-text sanitizer policy (core default).",
	}
	slots := KnownProviderSlots()
	out := make([]ProviderSlotInfo, 0, len(slots))
	for _, slot := range slots {
		desc := notes[slot]
		if desc == "" {
			desc = "Host-owned provider slot."
		}
		out = append(out, ProviderSlotInfo{Slot: slot, Description: desc})
	}
	return out
}

func joinOrDash(items []string) string {
	if len(items) == 0 {
		return "—"
	}
	parts := make([]string, len(items))
	for i, item := range items {
		parts[i] = "`" + item + "`"
	}
	return strings.Join(parts, ", ")
}

func escapePipes(s string) string {
	return strings.ReplaceAll(s, "|", "\\|")
}

func formatDuration(d time.Duration) string {
	if d == 0 {
		return "—"
	}
	if d%time.Hour == 0 {
		h := int(d / time.Hour)
		if h%24 == 0 {
			return fmt.Sprintf("%dd", h/24)
		}
		return fmt.Sprintf("%dh", h)
	}
	if d%time.Minute == 0 {
		return fmt.Sprintf("%dm", int(d/time.Minute))
	}
	return d.String()
}

// DefaultCatalogDocsDir 相对仓库根的默认输出目录。
const DefaultCatalogDocsDir = "docs/extensions/catalogs"

// ResolveCatalogDocsDir 在已知 repo root 下解析输出目录。
func ResolveCatalogDocsDir(repoRoot, override string) string {
	if strings.TrimSpace(override) != "" {
		if filepath.IsAbs(override) {
			return override
		}
		return filepath.Join(repoRoot, override)
	}
	return filepath.Join(repoRoot, DefaultCatalogDocsDir)
}

// DocFileNames 返回稳定排序的生成文件名列表。
func DocFileNames() []string {
	names := []string{
		DocIndex,
		DocEvents,
		DocCapabilities,
		DocContributionPoints,
		DocProviderSlots,
		DocSchedules,
	}
	sort.Strings(names)
	return names
}
