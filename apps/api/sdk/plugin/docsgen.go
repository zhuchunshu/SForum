func renderEvents() string {
	var b strings.Builder
	b.WriteString(renderHeader(
		"Event catalog",
		"Plugins declare listeners only for events in this catalog. "+
			"**filter/validate** run synchronously on the write path — keep them cheap; "+
			"enqueue River jobs for heavy work. **observe** is asynchronous.",
	))
	b.WriteString("| Name | Kind | Timeout (ms) | Failure policy | Payload | Patch |\n")
	b.WriteString("| --- | --- | ---: | --- | --- | --- |\n")
	for _, e := range EventCatalog() {
		payload := joinOrDash(e.PayloadFields)
		patch := joinOrDash(e.PatchFields)
		b.WriteString(fmt.Sprintf("| `%s` | %s | %d | %s | %s | %s |\n",
			e.Name, e.Kind, e.TimeoutMS, e.FailurePolicy, payload, patch))
	}
	b.WriteString("\n### Descriptions\n\n")
	for _, e := range EventCatalog() {
		b.WriteString(fmt.Sprintf("#### `%s`\n\n", e.Name))
		b.WriteString(e.Description)
		b.WriteString("\n\n")
	}
	return b.String()
}

func renderCapabilities() string {
	var b strings.Builder
	b.WriteString(renderHeader(
		"Capability catalog",
		"Capabilities constrain **plugin processes**, not end-user RBAC. "+
			"Declare `capabilities` in the manifest; the host may imply a minimal set "+
			"from backend/settings/jobs/`mail.provider`. First enable requires operator confirmation.",
	))
	b.WriteString("| Key | Risk | Label (EN) | Label (ZH) | Description |\n")
	b.WriteString("| --- | --- | --- | --- | --- |\n")
	for _, c := range CapabilityCatalog() {
		b.WriteString(fmt.Sprintf("| `%s` | %s | %s | %s | %s |\n",
			c.Key, c.Risk, escapePipes(c.LabelEN), escapePipes(c.LabelZH), escapePipes(c.Description)))
	}
	b.WriteString("\n### Risk tiers\n\n")
	b.WriteString("- **low** — routine host calls (Host API surface, own settings, permission checks)\n")
	b.WriteString("- **medium** — side effects operators should review (enqueue jobs, append audit)\n")
	b.WriteString("- **high** — sensitive data or network (user reads, outbound network)\n")
	return b.String()
}

