// GeneratedDocs 是一次目录文档生成的结果（内存）。
type GeneratedDocs struct {
	// Files 相对输出根的路径 → Markdown 正文。
	Files map[string]string
}

// 生成文件名（相对 catalogs 输出目录）。
const (
	DocIndex              = "README.md"
	DocEvents             = "events.md"
	DocCapabilities       = "capabilities.md"
	DocContributionPoints = "contribution-points.md"
	DocProviderSlots      = "provider-slots.md"
	DocSchedules          = "schedules.md"
)

// genMarker 出现在每个生成文件顶部；人工编辑应改代码目录，再 re-generate。
const genMarker = "<!-- Generated by: sforum extension docs generate. Do not edit by hand. -->"

// GenerateCatalogDocs 从当前进程内的宿主目录生成 Markdown 文档集。
func GenerateCatalogDocs() GeneratedDocs {
	ensureNL := func(s string) string {
		if !strings.HasSuffix(s, "\n") {
			return s + "\n"
		}
		return s
	}
	files := map[string]string{
		DocIndex:              ensureNL(renderIndex()),
		DocEvents:             ensureNL(renderEvents()),
		DocCapabilities:       ensureNL(renderCapabilities()),
		DocContributionPoints: ensureNL(renderContributionPoints()),
		DocProviderSlots:      ensureNL(renderProviderSlots()),
		DocSchedules:          ensureNL(renderSchedules()),
	}
	return GeneratedDocs{Files: files}
}

// WriteCatalogDocs 将生成结果写入 dir（创建缺失目录，覆盖同名文件）。
func WriteCatalogDocs(dir string) error {
	docs := GenerateCatalogDocs()
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	// 稳定写入顺序，便于 diff 与测试。
	names := make([]string, 0, len(docs.Files))
	for name := range docs.Files {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		path := filepath.Join(dir, name)
		body := docs.Files[name]
		if !strings.HasSuffix(body, "\n") {
			body += "\n"
		}
		if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
			return fmt.Errorf("write %s: %w", path, err)
		}
	}
	return nil
}

// CheckCatalogDocs 比较 dir 中已有文件与重新生成内容是否一致。
// 返回 (ok, 差异说明)。ok=true 表示无漂移。
func CheckCatalogDocs(dir string) (bool, string) {
	docs := GenerateCatalogDocs()
	var diffs []string
	for name, want := range docs.Files {
		path := filepath.Join(dir, name)
		got, err := os.ReadFile(path)
		if err != nil {
			diffs = append(diffs, fmt.Sprintf("missing %s: %v", name, err))
			continue
		}
		if string(got) != want {
			diffs = append(diffs, fmt.Sprintf("drift in %s", name))
		}
	}
	// 报告多余文件（同目录下非预期 .md 不强制失败，避免夹带手写说明时误伤）。
	if len(diffs) == 0 {
		return true, ""
	}
	sort.Strings(diffs)
	return false, strings.Join(diffs, "\n")
}

func renderHeader(title, intro string) string {
	var b strings.Builder
	b.WriteString(genMarker)
	b.WriteByte('\n')
	b.WriteString("# ")
	b.WriteString(title)
	b.WriteString("\n\n")
	b.WriteString(intro)
	b.WriteString("\n\n")
	b.WriteString("Source of truth: Go catalogs under `apps/api` ")
	b.WriteString("(`app/Support/Events`, `Capabilities`, `ExtensionManifest`, ")
	b.WriteString("`Jobs`, and provider slot constants). Regenerate with:\n\n")
	b.WriteString("```bash\n")
	b.WriteString("cd apps/api && go run ./cmd/sforum extension docs generate\n")
	b.WriteString("```\n\n")
	b.WriteString("Or verify CI drift:\n\n")
	b.WriteString("```bash\n")
	b.WriteString("cd apps/api && go run ./cmd/sforum extension docs generate --check\n")
	b.WriteString("```\n\n")
	return b.String()
}

